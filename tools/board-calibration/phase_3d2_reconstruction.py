"""Phase 3D.2 evidence inventory and conservative station recovery audit.

This pass deliberately separates three things that are easy to conflate:
the printed sequence visible in the photographs, a detected physical marker,
and a defensible marker-to-station assignment.  It consumes the Phase 3D.1
artifacts, preserves their feature identifiers, and emits audit-friendly
deliverables without inventing identities for unresolved markers.
"""

from __future__ import annotations

import hashlib
import json
import math
from pathlib import Path
from typing import Any


HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
EVIDENCE = REPO / "docs" / "game" / "evidence" / "board-photos"
OUT = HERE / "output" / "station_recovery"
OUT.mkdir(parents=True, exist_ok=True)

CANVAS = (1350, 1000)
PRIMARY = {
    "complete.jpeg": {"folder": "original-references", "orientation": "landscape", "region": "full board; global reference"},
    "top-left.jpeg": {"folder": "original-references", "orientation": "portrait; rotated CCW", "region": "north-west; stations 1-114"},
    "top-right.jpeg": {"folder": "original-references", "orientation": "portrait; rotated CCW", "region": "north-east; stations 4-107"},
    "bottom-left.jpeg": {"folder": "original-references", "orientation": "portrait; rotated CCW", "region": "south-west; stations 113-197"},
    "bottom-right.jpeg": {"folder": "original-references", "orientation": "portrait; rotated CCW", "region": "south-east; stations 113-200"},
}
CLOSEUPS = {f"closeup-{i:02d}.jpg": "local detail; station-marker inspection" for i in range(1, 7)}


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for block in iter(lambda: fh.read(1024 * 1024), b""):
            h.update(block)
    return h.hexdigest().upper()


def dimensions(path: Path) -> tuple[int, int]:
    # OpenCV is already a required calibration dependency.
    import cv2

    image = cv2.imread(str(path), cv2.IMREAD_UNCHANGED)
    if image is None:
        raise RuntimeError(f"Unable to read evidence image: {path}")
    height, width = image.shape[:2]
    return width, height


def write_photo_inventory() -> list[dict[str, Any]]:
    records: list[dict[str, Any]] = []
    for name, info in PRIMARY.items():
        path = EVIDENCE / info["folder"] / name
        if not path.exists():
            records.append({"filename": name, "status": "missing", "expected_path": str(path.relative_to(REPO))})
            continue
        width, height = dimensions(path)
        records.append({"filename": name, "path": str(path.relative_to(REPO)), "dimensions": [width, height],
                        "sha256": sha256(path), "orientation": info["orientation"],
                        "useful_board_region": info["region"], "quality": "original photographic evidence",
                        "coverage": info["region"], "overlaps": "complete.jpeg plus adjacent quadrant views"})
    for name, role in CLOSEUPS.items():
        path = EVIDENCE / "closeups" / name
        if not path.exists():
            records.append({"filename": name, "status": "missing", "expected_path": str(path.relative_to(REPO))})
            continue
        width, height = dimensions(path)
        records.append({"filename": name, "path": str(path.relative_to(REPO)), "dimensions": [width, height],
                        "sha256": sha256(path), "orientation": "portrait; board rotated in frame",
                        "useful_board_region": role, "quality": "close-up photographic evidence",
                        "coverage": "local marker detail", "overlaps": "not independently registered by this pass"})
    (EVIDENCE / "PHOTO-INVENTORY.md").write_text(
        "# Board-photo inventory\n\n"
        "Generated by `phase_3d2_reconstruction.py`. Original photographs are read-only inputs; no image was replaced or resized.\n\n"
        + "\n".join(f"- `{r['filename']}` — {r.get('dimensions', 'unavailable')}; SHA-256 `{r.get('sha256', 'n/a')}`; {r.get('useful_board_region', r.get('status'))}." for r in records)
        + "\n\nThe five original references are used for global geometry and quadrant evidence. Six close-ups are retained as local visual evidence; this pass does not silently treat a stitched/rectified output as an original photograph.\n",
        encoding="utf-8")
    return records


def load_json(name: str) -> Any:
    return json.loads((OUT / name).read_text(encoding="utf-8"))


def finite_norm(x: Any) -> bool:
    return isinstance(x, (int, float)) and math.isfinite(float(x)) and 0 <= float(x) <= 1


def main() -> None:
    import cv2
    import numpy as np

    photos = write_photo_inventory()
    matrix = load_json("station_identities_matrix.json")
    candidates = load_json("candidate_marker_inventory.json")
    raw = json.loads((HERE / "output" / "coordinate_extraction" / "coordinate_inventory.json").read_text(encoding="utf-8"))
    reconciled = json.loads((HERE / "output" / "coordinate_extraction" / "reconciled_coordinate_inventory.json").read_text(encoding="utf-8"))
    entries = matrix["identities_1_to_199"]
    assert [e["station_id"] for e in entries] == list(range(1, 200))
    assert len(raw) == 138 and len(reconciled["features"]) == 121

    counts = {status: sum(e["status"] == status for e in entries) for status in
              ("verified", "candidate_uncertain", "missing_from_evidence", "conflicting", "duplicate")}
    assigned = [e for e in entries if e["status"] in ("verified", "candidate_uncertain")]
    feature_ids = {f["provisional_feature_id"] for f in candidates["physical_marker_candidates"]}
    assert len({e["feature_id"] for e in assigned}) == len(assigned)
    assert all(e["feature_id"] in feature_ids for e in assigned)
    assert all(finite_norm(e["pixel_x"] / CANVAS[0]) and finite_norm(e["pixel_y"] / CANVAS[1]) for e in assigned)
    assert all(e["station_id"] != 200 for e in entries)

    inventory = []
    evidence = []
    for e in entries:
        x = e["pixel_x"] / CANVAS[0] if e["pixel_x"] is not None else None
        y = e["pixel_y"] / CANVAS[1] if e["pixel_y"] is not None else None
        inventory.append({**e, "normalized_x": x, "normalized_y": y,
                          "source_images": [s.strip() for s in (e.get("evidence_source") or "").split("&") if s.strip()],
                          "source_coordinates": {"canvas": [e["pixel_x"], e["pixel_y"]] if x is not None else None}})
        evidence.append({"station_id": e["station_id"], "assignment_status": e["status"],
                         "identity_evidence": e.get("evidence_source"),
                         "source_coordinate": [e["pixel_x"], e["pixel_y"]] if x is not None else None,
                         "identity_evidence_limit": "No defensible marker-to-number assignment established in Phase 3D.2" if e["status"] == "missing_from_evidence" else None})

    base = {"phase": "3D.2", "coordinate_system": {"origin": "top-left", "x": "right", "y": "down", "canvas": list(CANVAS)},
            "summary_counts": counts, "source_photo_count": len(photos), "raw_observation_count_preserved": len(raw),
            "baseline_feature_count_preserved": len(reconciled["features"]), "marker_200_excluded": True}
    (OUT / "station_inventory.json").write_text(json.dumps({"metadata": base, "stations": inventory}, indent=2), encoding="utf-8")
    (OUT / "station_evidence_mapping.json").write_text(json.dumps({"metadata": base, "stations": evidence,
        "marker_200": matrix["metadata"]["additional_physical_markers"][0]}, indent=2), encoding="utf-8")
    (OUT / "station_recovery_completeness.json").write_text(json.dumps({"metadata": base, "entries": entries}, indent=2), encoding="utf-8")

    report = f"""# Station recovery final report — Phase 3D.2

## Result

All 199 playable station ID slots are represented exactly once. This is an accounting result, not a claim that every identity was recovered.

| status | count |
|---|---:|
| verified | {counts['verified']} |
| candidate-uncertain | {counts['candidate_uncertain']} |
| missing from evidence | {counts['missing_from_evidence']} |
| conflicting | {counts['conflicting']} |
| duplicate | {counts['duplicate']} |

Verified assignments remain Station 1 → FEAT_0094 and Station 199 → FEAT_0115. Candidate assignments remain 3, 120, 123 and 158. Marker 200 is recorded separately and excluded from the playable inventory.

## Evidence and limitation

The source set contains five original references and six close-ups. The close-ups visibly show many printed labels, and the existing board inventory records the observed 1–200 sequence. However, the existing calibrated feature inventory does not contain a traceable, independently documented feature match for the remaining printed labels. Those entries remain `missing_from_evidence` rather than being promoted from landmark or proximity inference.

The previous Phase 3D.1 result was 2 verified, 4 candidate-uncertain, 193 missing, 0 conflicting and 0 duplicate. Phase 3D.2 preserves those assignments and adds a machine-readable evidence map, photo inventory and completeness audit.

## Spatial fidelity

The common coordinate system is the existing 1350×1000 provisional canvas, normalized from the top-left. Coordinates are present for all six assigned entries and for the 145 physical-marker candidates in the preserved candidate inventory. The canvas aspect ratio remains provisional; no single homography or photographic panorama is asserted as physical truth.
"""
    (OUT / "station_recovery_final_report.md").write_text(report, encoding="utf-8")
    (OUT / "station_recovery_completeness.md").write_text("# Station recovery completeness\n\n" + json.dumps(counts, indent=2) + "\n\nEvery integer ID from 1 through 199 appears exactly once. Missing entries are explicit and carry null coordinates; no missing entry is silently verified.\n", encoding="utf-8")
    (OUT / "station_coordinate_quality_report.md").write_text("# Station coordinate quality\n\nAssigned coordinates use the existing calibrated 1350×1000 canvas and are normalized as `x/1350`, `y/1000`. The six identity-assigned coordinates are finite and in range. Candidate physical-marker coordinates remain in `candidate_marker_inventory.json`; they are not station identities.\n\nCoordinate confidence is not uniform: the original full-board reference provides global placement, while quadrant photographs provide local refinement. The six close-ups are retained as evidence but are not independently registered by this pass.\n", encoding="utf-8")

    # Visuals are rendered from the existing calibrated canvas and quadrant
    # registrations.  No source photograph is written to or modified.
    assigned_by_feature = {e["feature_id"]: e for e in assigned}
    full_path = HERE / "output" / "rectified_complete.png"
    full = cv2.imread(str(full_path))
    if full is not None:
        confidence = cv2.addWeighted(full, 0.72, np.zeros_like(full), 0.28, 0)
        for feature in candidates["physical_marker_candidates"]:
            x, y = int(round(feature["pixel_x"])), int(round(feature["pixel_y"]))
            identity = assigned_by_feature.get(feature["provisional_feature_id"])
            colour = (0, 220, 0) if identity and identity["status"] == "verified" else ((0, 180, 255) if identity else (150, 150, 150))
            cv2.circle(confidence, (x, y), 6, colour, 2)
            if identity:
                cv2.putText(confidence, str(identity["station_id"]), (x + 7, y + 4), cv2.FONT_HERSHEY_SIMPLEX, 0.32, colour, 1, cv2.LINE_AA)
        cv2.putText(confidence, "Phase 3D.2 confidence: green=verified, amber=candidate, gray=unassigned physical marker", (18, 28), cv2.FONT_HERSHEY_SIMPLEX, 0.46, (255, 255, 255), 2, cv2.LINE_AA)
        cv2.imwrite(str(OUT / "station_confidence_map.png"), confidence)

        for region in ("top-left", "top-right", "bottom-left", "bottom-right"):
            region_path = HERE / "output" / f"registered_{region}.png"
            region_img = cv2.imread(str(region_path))
            if region_img is None:
                continue
            for identity in assigned:
                x, y = int(round(identity["pixel_x"])), int(round(identity["pixel_y"]))
                if 0 <= x < region_img.shape[1] and 0 <= y < region_img.shape[0]:
                    colour = (0, 220, 0) if identity["status"] == "verified" else (0, 180, 255)
                    cv2.circle(region_img, (x, y), 8, colour, 2)
                    cv2.putText(region_img, str(identity["station_id"]), (x + 8, y + 4), cv2.FONT_HERSHEY_SIMPLEX, 0.34, colour, 1, cv2.LINE_AA)
            cv2.imwrite(str(OUT / f"regional_numbered_overlay_{region}.png"), region_img)

        # A compact evidence contact sheet uses registered views only as a
        # review aid; it is explicitly not treated as a replacement original.
        panels = []
        for region in ("top-left", "top-right", "bottom-left", "bottom-right"):
            image = cv2.imread(str(HERE / "output" / f"registered_{region}.png"))
            if image is not None:
                image = cv2.resize(image, (540, 400), interpolation=cv2.INTER_AREA)
                cv2.putText(image, region, (12, 28), cv2.FONT_HERSHEY_SIMPLEX, 0.8, (255, 255, 255), 2, cv2.LINE_AA)
                panels.append(image)
        if len(panels) == 4:
            sheet = np.vstack((np.hstack((panels[0], panels[1])), np.hstack((panels[2], panels[3]))))
            cv2.imwrite(str(OUT / "regional_evidence_contact_sheet.png"), sheet)

    print(json.dumps({"photos": len(photos), "counts": counts, "stations": len(entries), "features": len(candidates["physical_marker_candidates"])}, indent=2))


if __name__ == "__main__":
    main()
